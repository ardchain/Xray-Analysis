const grid = attr({x1:0,x2:300,y1:0,y2:0});
const native = offset => ({querySelectorAll:()=>[200,100,0].map(x=>attr({x:x+offset,width:30}))});
const svg = {querySelector:()=>grid, querySelectorAll:selector=>selector.includes('grid') ? [grid,attr({y1:100,y2:100})] : [native(10),native(45)]};
const layout = context.selection.layout(svg,3);
