const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
let source = fs.readFileSync(require('node:path').join(__dirname, '..', 'panel.js'), 'utf8');
const boundary = source.lastIndexOf('  window.addEventListener("message"');
source = source.slice(0, boundary) + 'globalThis.selection = { choose: commitExtraMetricSelection, values: selectedExtraBySlot, layout: getNativeLayout }; getAxisLabelGroups = () => [];\n})();';
const context = {window:{}};
vm.runInNewContext(source, context);
const {choose, values} = context.selection;
assert.equal(choose(0,'HomeLinger'), true);
assert.deepEqual(Array.from(values), ['HomeLinger',null]);
assert.equal(choose(1,'HomeLinger'), false);
assert.deepEqual(Array.from(values), ['HomeLinger',null]);
